/** 문자열 → 안정적인 정수. 세이브를 거쳐도 같은 회사엔 같은 라이벌이 붙는다 */
function hash(str) {
  let h = 0;
  for (let i = 0; i < String(str).length; i++) h = (h * 31 + String(str).charCodeAt(i)) | 0;
  return Math.abs(h);
}

